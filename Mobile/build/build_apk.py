"""Build a signed, bundled APK locally; no Expo account or paid service required."""
import argparse
import hashlib
import json
import os
import secrets
import shutil
import subprocess
import zipfile
from pathlib import Path
from urllib.parse import urlsplit


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('app',choices=['user','admin'])
    parser.add_argument('--public-url',required=True,help='HTTPS origin, e.g. https://demo.duckdns.org')
    parser.add_argument('--http-demo',action='store_true',help='Explicitly allow HTTP only for this demo API host')
    parser.add_argument('--version-code',type=int,default=2)
    parser.add_argument('--abis',default='arm64-v8a,x86_64',help='Phone and emulator architectures')
    parser.add_argument('--prepare-only',action='store_true',help='Generate and configure the native project without compiling')
    parser.add_argument('--native-jobs',type=int,choices=[1,2],default=1,help='Concurrent C++ compilations; keep 1 on low-memory machines')
    args=parser.parse_args()
    url=urlsplit(args.public_url)
    if url.scheme not in ['http','https'] or not url.hostname or url.path not in ['','/'] or url.query or url.fragment or url.username or url.password:parser.error('Use an HTTP(S) origin without a path')
    if url.scheme=='http' and not args.http_demo:parser.error('HTTP needs --http-demo')
    if args.version_code<1:parser.error('version-code must be positive')
    if not set(args.abis.split(','))<={'arm64-v8a','x86_64','armeabi-v7a','x86'}:parser.error('Invalid ABI')
    project=Path(__file__).resolve().parents[2]
    app=project/'Mobile'/(args.app+'-app')
    tools=Path.home()/'.local/share/ticketpro-android'
    jdk=Path(os.environ.get('JAVA_HOME',str(tools/'jdk')))
    sdk=Path(os.environ.get('ANDROID_HOME',str(tools/'sdk')))
    if not (jdk/'bin/java').exists() or not (sdk/'platform-tools/adb').exists():raise SystemExit('Install JDK and Android SDK; set JAVA_HOME and ANDROID_HOME')
    env=os.environ.copy()
    env.update(JAVA_HOME=str(jdk),ANDROID_HOME=str(sdk),ANDROID_SDK_ROOT=str(sdk),
        PATH=str(jdk/'bin')+os.pathsep+env['PATH'],TICKETPRO_PUBLIC_URL=args.public_url.rstrip('/'),
        TICKETPRO_HTTP_DEMO='1' if args.http_demo else '0',TICKETPRO_BUILD_MODE='release',
        TICKETPRO_VERSION_CODE=str(args.version_code),EXPO_PUBLIC_TICKET_API_URL=args.public_url.rstrip('/')+'/api',
        EXPO_PUBLIC_AUTH_API_URL=args.public_url.rstrip('/')+'/api',NODE_ENV='production',CI='1',EXPO_NO_TELEMETRY='1',
        NODE_OPTIONS='--max-old-space-size=1024',CMAKE_BUILD_PARALLEL_LEVEL=str(args.native_jobs),TICKETPRO_NATIVE_JOBS=str(args.native_jobs))
    env['EXPO_PUBLIC_TICKET_WEB_URL']=args.public_url.rstrip('/') if url.scheme=='https' or url.port!=8000 else f'http://{url.hostname}:5173'
    if not (app/'node_modules/.bin/expo').exists():subprocess.run(['npm','ci','--include=dev'],cwd=app,env=env,check=True)
    native=app/'android'
    if native.exists() and not (native/'.ticketpro-generated').exists():raise SystemExit('Existing native project found. Review it before regenerating.')
    subprocess.run([str(app/'node_modules/.bin/expo'),'prebuild','--platform','android','--no-install'],cwd=app,env=env,check=True)
    (native/'.ticketpro-generated').write_text('Generated by Mobile/build/build_apk.py\n')
    private=Path.home()/'.local/share/ticketpro-signing'
    private.mkdir(parents=True,exist_ok=True);private.chmod(0o700)
    metadata=private/'demo-signing.json';keystore=private/'ticketpro-demo.keystore'
    if metadata.exists():credentials=json.loads(metadata.read_text())
    else:
        if keystore.exists():raise SystemExit('Keystore exists without metadata; recover signing credentials first')
        credentials={'alias':'ticketpro-demo','password':secrets.token_urlsafe(32)}
        descriptor=os.open(metadata,os.O_WRONLY|os.O_CREAT|os.O_EXCL,0o600)
        with os.fdopen(descriptor,'w') as out:json.dump(credentials,out)
    env.update(TICKETPRO_KEYSTORE=str(keystore),TICKETPRO_KEY_ALIAS=credentials['alias'],TICKETPRO_KEY_PASSWORD=credentials['password'])
    if not keystore.exists():
        subprocess.run([str(jdk/'bin/keytool'),'-genkeypair','-keystore',str(keystore),'-storepass:env','TICKETPRO_KEY_PASSWORD','-keypass:env','TICKETPRO_KEY_PASSWORD','-alias',credentials['alias'],'-keyalg','RSA','-keysize','2048','-validity','10000','-dname','CN=TicketPro Demo, O=TicketPro Graduation Project, C=KR'],env=env,check=True)
        keystore.chmod(0o600)
    gradle=native/'app/build.gradle';text=gradle.read_text()
    if 'ticketproSigning' not in text:
        marker='signingConfigs {'
        if marker not in text or 'signingConfig signingConfigs.debug' not in text:raise SystemExit('Unexpected Gradle signing template')
        text=text.replace(marker,marker+'''
        ticketproSigning {
            storeFile file(System.getenv("TICKETPRO_KEYSTORE"))
            storePassword System.getenv("TICKETPRO_KEY_PASSWORD")
            keyAlias System.getenv("TICKETPRO_KEY_ALIAS")
            keyPassword System.getenv("TICKETPRO_KEY_PASSWORD")
        }
''',1)
        text=text.replace('signingConfig signingConfigs.debug','signingConfig signingConfigs.ticketproSigning')
        gradle.write_text(text)
    (native/'local.properties').write_text('sdk.dir='+str(sdk)+'\n')
    if args.prepare_only:
        print(json.dumps({'native_project':str(native),'prepared':True}),flush=True)
        return
    subprocess.run(['./gradlew','app:assembleRelease','--no-daemon','--no-parallel','--max-workers=1',
        '--init-script',str(project/'Mobile/build/low_memory.gradle'),
        '-Dorg.gradle.jvmargs=-Xmx1024m -XX:MaxMetaspaceSize=512m -Dfile.encoding=UTF-8',
        '-PreactNativeArchitectures='+args.abis,'-Porg.gradle.parallel=false','-Pkotlin.compiler.execution.strategy=in-process'],cwd=native,env=env,check=True)
    built=native/'app/build/outputs/apk/release/app-release.apk'
    output=project/'artifacts';output.mkdir(exist_ok=True)
    flavor='-http-demo' if args.http_demo else ''
    target=output/f'ticketpro-{args.app}{flavor}-v{args.version_code}.apk'
    shutil.copy2(built,target)
    with zipfile.ZipFile(target) as archive:
        if 'assets/index.android.bundle' not in archive.namelist():raise RuntimeError('APK is missing its offline JavaScript bundle')
        for abi in args.abis.split(','):
            if not any(name.startswith('lib/'+abi+'/') for name in archive.namelist()):raise RuntimeError('APK is missing ABI '+abi)
    badging=subprocess.check_output([str(sdk/'build-tools/36.0.0/aapt'),'dump','badging',str(target)],env=env,text=True)
    if "name='com.ticketpro.demo."+args.app+"'" not in badging:raise RuntimeError('Unexpected APK package name')
    if 'application-debuggable' in badging:raise RuntimeError('APK must be a non-debuggable release build')
    verifier=sdk/'build-tools/36.0.0/apksigner'
    subprocess.run([str(verifier),'verify','--verbose',str(target)],env=env,check=True)
    manifest={'app':args.app,'version_code':args.version_code,'public_url':args.public_url,'http_demo':args.http_demo,'abis':args.abis.split(','),'sha256':hashlib.sha256(target.read_bytes()).hexdigest()}
    target.with_suffix('.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print(json.dumps({'apk':str(target),'sha256':manifest['sha256'],'signing_key_directory':str(private)}),flush=True)


if __name__=='__main__':main()
